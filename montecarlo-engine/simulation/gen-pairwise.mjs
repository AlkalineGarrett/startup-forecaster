// Bake the Pairwise matrix into the portfolio (config `generated.pairwise`) so the artifact renders it
// with no in-browser simulation on the default view. It is the engine's computation (src/pairwise.ts, the same
// one the results UI's server and precompute run — no mirrored copy of the pairing rules), reduced to the
// scalars the pairwise/horizons renderers read. Deterministic (fixed seed). A project edit in the live app
// invalidates it and the app recomputes. Re-bake whenever the model changes (golden moved).
//
//   node simulation/gen-pairwise.mjs        (--skip / SKIP_PAIRWISE=1 leaves the file as-is, now stale)
//
// The simulation build (simulation/results.mjs) bakes the matrix it already computed through writePairwise.
import { writeFileSync } from "node:fs";
import { isMain } from "../../shared/is-main.mjs";
import { CONFIG } from "../config.mjs";

const hz = (h) => ({ p20: h.p20, p50: h.p50, p80: h.p80 });
const lite = (r) => (r ? { p20: r.p20, p50: r.p50, p80: r.p80, h3: hz(r.h3), h12: hz(r.h12), h25: hz(r.h25),
  afterTax20: r.afterTax20, afterTax50: r.afterTax50, afterTax80: r.afterTax80, afterTaxMean: r.afterTaxMean } : null);

/** The generated module for a computed matrix (computePairwise's PairMatrix). */
export function pairwiseModule(m) {
  const data = { labels: m.labels, solo: m.solo.map(lite), res: m.res.map((row) => row.map(lite)) };
  const body = `// AUTO-GENERATED by montecarlo-engine simulation/gen-pairwise.mjs. The Pairwise matrix precomputed at build
// time so the artifact renders it with no in-browser simulation on the default (unedited) view.
// Deterministic (fixed SEED) — identical to the engine's computePairwise(). Only the scalars the renderers
// read are baked (p20/p50/p80 + h3/h12/h25 + after-tax). Regenerate whenever the model changes.
// Portfolio data: attaches the precomputed pairwise matrix to the engine via configurePortfolio().
import { configurePortfolio, type PairwiseLite } from "${CONFIG.engineImport}/portfolio-context.ts";

// Cast: only the fields renderPairwise + horizonsTable read are populated.
configurePortfolio({ pairwisePrecomputed: ${JSON.stringify(data)} as unknown as PairwiseLite });
`;
  const cells = data.solo.length + data.res.reduce((s, row) => s + row.filter(Boolean).length, 0);
  return { body, projects: data.labels.length, cells };
}

/** Write the matrix to the config's `generated.pairwise`; returns a one-line summary. */
export function writePairwise(m, file = CONFIG.generated.pairwise) {
  const { body, projects, cells } = pairwiseModule(m);
  writeFileSync(file, body);
  return `Wrote ${file.split("/").pop()}: ${projects} projects, ${cells} cells`;
}

if (isMain(import.meta.url)) {
  if (!CONFIG.generated.pairwise) { console.log("gen-pairwise: no `generated.pairwise` in the config — nothing to do."); process.exit(0); }
  if (process.argv.includes("--skip") || process.env.SKIP_PAIRWISE) {
    console.log("gen-pairwise: skipped — the baked matrix is STALE until re-run.");
    process.exit(0);
  }
  const { loadPortfolio } = await import("../portfolio-loader.mjs");
  await loadPortfolio();
  const { runPortfolio, computePairwise } = await import("../src/pairwise.ts");
  const t0 = performance.now();
  const m = await computePairwise(runPortfolio());
  console.log(`${writePairwise(m)} in ${((performance.now() - t0) / 1000).toFixed(1)}s.`);
}
