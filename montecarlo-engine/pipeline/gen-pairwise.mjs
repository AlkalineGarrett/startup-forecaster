// Bake the Pairwise matrix into the portfolio (config `generated.pairwise`) so the artifact renders it
// with no in-browser simulation on the default view. It is appcore's own computation (the same one
// precompute/server run — no mirrored copy of the pairing rules), reduced to the scalars the
// pairwise/horizons renderers read. Deterministic (fixed seed). A project edit in the live app
// invalidates it and the app recomputes. Re-bake whenever the model changes (golden moved).
//
//   node pipeline/gen-pairwise.mjs        (--skip / SKIP_PAIRWISE=1 leaves the file as-is, now stale)
import { writeFileSync } from "node:fs";
import { CONFIG } from "../config.mjs";
import { loadPortfolio } from "../portfolio-loader.mjs";

if (!CONFIG.generated.pairwise) { console.log("gen-pairwise: no `generated.pairwise` in the config — nothing to do."); process.exit(0); }
if (process.argv.includes("--skip") || process.env.SKIP_PAIRWISE) {
  console.log("gen-pairwise: skipped — the baked matrix is STALE until re-run.");
  process.exit(0);
}
await loadPortfolio();
const ac = await import("../src/appcore.ts");
const t0 = performance.now();
ac.initAppcore();
await ac.computePairwiseAsync();
const m = ac.pairwiseMatrix();

const hz = (h) => ({ p20: h.p20, p50: h.p50, p80: h.p80 });
const lite = (r) => (r ? { p20: r.p20, p50: r.p50, p80: r.p80, h3: hz(r.h3), h12: hz(r.h12), h25: hz(r.h25),
  afterTax20: r.afterTax20, afterTax50: r.afterTax50, afterTax80: r.afterTax80, afterTaxMean: r.afterTaxMean } : null);
const data = { labels: m.labels, solo: m.solo.map(lite), res: m.res.map((row) => row.map(lite)) };

const body = `// AUTO-GENERATED by montecarlo-engine pipeline/gen-pairwise.mjs. The Pairwise matrix precomputed at build
// time so the artifact renders it with no in-browser simulation on the default (unedited) view.
// Deterministic (fixed SEED) — identical to appcore computePairwiseAsync(). Only the scalars the renderers
// read are baked (p20/p50/p80 + h3/h12/h25 + after-tax). Regenerate whenever the model changes.
// Portfolio data: attaches the precomputed pairwise matrix to the engine via configurePortfolio().
import { configurePortfolio, type PairwiseLite } from "${CONFIG.engineImport}/portfolio-context.ts";

// Cast: only the fields renderPairwise + horizonsTable read are populated.
configurePortfolio({ pairwisePrecomputed: ${JSON.stringify(data)} as unknown as PairwiseLite });
`;
writeFileSync(CONFIG.generated.pairwise, body);
const cells = data.solo.length + data.res.reduce((s, row) => s + row.filter(Boolean).length, 0);
console.log(`Wrote ${CONFIG.generated.pairwise.split("/").pop()}: ${data.labels.length} projects, ${cells} cells in ${((performance.now() - t0) / 1000).toFixed(1)}s.`);
