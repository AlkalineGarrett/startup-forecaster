// Generate the portfolio's evidence module (config `generated.evidence`) — the grounding layer for the
// "Grounding" tab. Bundles the corpus of the config's `distributionData` project (observations +
// general-knowledge + speculations), resolves each observation's source doc to a URL/title through the
// `groundingSources` registry (documents.json; optional), and indexes which corpus entries each compiled
// node references. The render layer joins this with DISTRIBUTIONS to show, per node, its construction
// and the evidence behind it.
//
//   node pipeline/gen-evidence.mjs      (run from the workspace, or MC_CONFIG=…)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CONFIG } from "../config.mjs";
import { compiledFiles, evidenceRefs } from "./compiled.mjs";

if (!CONFIG.distributionData || !CONFIG.generated.evidence) {
  console.log("gen-evidence: no `distributionData` / `generated.evidence` in the config — nothing to do.");
  process.exit(0);
}
const GDD = CONFIG.distributionData;
const DOCS = CONFIG.groundingSources ? join(CONFIG.groundingSources, "documents.json") : null;
const OUT = CONFIG.generated.evidence;

const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const docs = DOCS && existsSync(DOCS) ? readJson(DOCS) : {};
const obs = readJson(join(GDD, "corpus", "observations.json"));
const gk = readJson(join(GDD, "corpus", "general-knowledge.json"));
const spec = readJson(join(GDD, "corpus", "speculations.json"));

// ---- CORPUS: every evidence item, source-doc resolved to url/title ----
const corpus = {};
for (const [id, o] of Object.entries(obs)) {
  const d = o.doc ? docs[o.doc] : null;
  corpus[id] = clean({
    kind: "obs",
    statement: o.statement,
    quote: o.quote,
    measure: o.measure,
    verification: o.verification || o.audit,
    url: d && d.url ? d.url : null,
    title: d && d.title ? d.title : null,
    // citedBy is filled below by inverting NODE_REFS — derived from the actual node references, never
    // stored on the corpus (a stored list drifts).
  });
}
for (const [id, o] of Object.entries(gk)) corpus[id] = clean({ kind: "gk", statement: o.statement, reasoning: o.reasoning, measure: o.measure });
for (const [id, o] of Object.entries(spec)) corpus[id] = clean({ kind: "spec", statement: o.statement, reasoning: o.reasoning, measure: o.measure });

function clean(o) {
  const r = {};
  for (const [k, v] of Object.entries(o)) if (v !== undefined && v !== null && !(Array.isArray(v) && !v.length)) r[k] = v;
  return r;
}

// ---- NODE_REFS: node key -> the corpus ids it references (deep-scan the compiled graph) ----
const nodeRefs = {};
for (const f of compiledFiles(GDD)) {
  const nodes = readJson(f).nodes || {};
  for (const [key, node] of Object.entries(nodes)) {
    const set = evidenceRefs(node, (id) => !!corpus[id]);
    if (set.size) nodeRefs[key] = [...set];
  }
}

// citedBy = the inverse of NODE_REFS (which nodes reference each corpus id) — always fresh.
for (const [key, ids] of Object.entries(nodeRefs))
  for (const id of ids) if (corpus[id]) (corpus[id].citedBy ||= []).push(key);

const nRefNodes = Object.keys(nodeRefs).length;
const banner = `// AUTO-GENERATED by montecarlo-engine pipeline/gen-evidence.mjs — do not edit. ${Object.keys(corpus).length} corpus items, ${nRefNodes} nodes indexed.\n`;
const body =
  banner +
  "// Portfolio data: attaches the evidence corpus + node references to the engine via configurePortfolio().\n" +
  `import { configurePortfolio } from "${CONFIG.engineImport}/portfolio-context.ts";\n\n` +
  "configurePortfolio({\n" +
  "  corpus: " + JSON.stringify(corpus, null, 1) + ",\n" +
  "  // node key (project::node or project::variant::node) -> corpus ids it references\n" +
  "  nodeRefs: " + JSON.stringify(nodeRefs, null, 0) + ",\n" +
  "});\n";

writeFileSync(OUT, body);
console.log(`Wrote ${OUT}: ${Object.keys(corpus).length} corpus items (${Object.keys(obs).length} obs / ${Object.keys(gk).length} gk / ${Object.keys(spec).length} spec), ${nRefNodes} nodes indexed.`);
